function uid(p){ return p + '_' + Date.now() + '_' + Math.random().toString(36).slice(2,8); }

function todayStr(){
  const d = new Date();
  const m = String(d.getMonth() + 1).padStart(2, '0');
  const day = String(d.getDate()).padStart(2, '0');
  return d.getFullYear() + '-' + m + '-' + day;
}
function monthStr(){ return todayStr().slice(0, 7); }
function yearNum(){ return new Date().getFullYear(); }

const WEEKDAYS = ["الأحد","الإثنين","الثلاثاء","الأربعاء","الخميس","الجمعة","السبت"];
const MONTHS = ["يناير","فبراير","مارس","أبريل","مايو","يونيو","يوليو","أغسطس","سبتمبر","أكتوبر","نوفمبر","ديسمبر"];

function fmtDateHuman(dateStr){
  const d = new Date(dateStr + 'T00:00:00');
  if (isNaN(d)) return dateStr;
  return WEEKDAYS[d.getDay()] + ' ' + d.getDate() + ' ' + MONTHS[d.getMonth()] + ' ' + d.getFullYear();
}

function fmtMoney(n){
  const num = Number(n) || 0;
  return num.toLocaleString('ar-EG', {maximumFractionDigits: 2}) + ' ج.م';
}

function esc(s){
  return (s == null ? '' : String(s)).replace(/[&<>"']/g, c => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
}

/* ----- Theme (day / night) ----- */
function getTheme(){ return localStorage.getItem('tahseel-theme') || 'dark'; }
function applyTheme(t){
  try { localStorage.setItem('tahseel-theme', t); } catch(e){}
  document.documentElement.setAttribute('data-theme', t);
  const meta = document.querySelector('meta[name="theme-color"]');
  if (meta) meta.setAttribute('content', t === 'dark' ? '#0E1318' : '#0FA67A');
}
function toggleTheme(){ applyTheme(getTheme() === 'dark' ? 'light' : 'dark'); render(); }

